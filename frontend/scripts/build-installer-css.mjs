// Builds backend/public/installer/installer.css with Tailwind from the classes used
// by the web installer (Blade view + plain JS). The output is committed so servers
// do not need Node.js to run /install. Usage: npm run build:installer-css
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { compile, optimize } from '@tailwindcss/node'
import { Scanner } from '@tailwindcss/oxide'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const backend = resolve(root, '../backend')
const sources = [
  resolve(backend, 'app/Modules/Installer/resources/views/installer.blade.php'),
  resolve(backend, 'public/installer/installer.js'),
]

const scanner = new Scanner({})
const candidates = scanner.scanFiles(sources.map((file) => ({ content: readFileSync(file, 'utf8'), extension: file.split('.').pop() })))

const input = '@import "tailwindcss";\n@layer base { :focus-visible { outline: 2px solid #3b6cf6; outline-offset: 2px; } }\n'
const compiler = await compile(input, { base: root, onDependency: () => {} })
const css = optimize(compiler.build(candidates), { minify: true }).code
const out = resolve(backend, 'public/installer/installer.css')
writeFileSync(out, `/* Generated by frontend/scripts/build-installer-css.mjs — do not edit. */\n${css}`)
console.log(`installer.css: ${css.length} bytes, ${candidates.length} candidates`)
